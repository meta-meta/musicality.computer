const assert=require('node:assert/strict');
const esbuild=require('esbuild');
const result=esbuild.buildSync({entryPoints:['src/lumatone/practice/detectedPitchCell.ts'],bundle:true,write:false,format:'cjs',platform:'node'});
const mod={exports:{}};new Function('module','exports',result.outputFiles[0].text)(mod,mod.exports);
const choose=mod.exports.detectedPitchCell;
const radius=27, viewport={left:-400,top:-250,width:800,height:500};
const cells=[];
for(let q=-20;q<=20;q++)for(let r=-10;r<=10;r++)cells.push({q,r,note:64+2*q+7*r,x:Math.sqrt(3)*(q+r/2)*radius,y:-1.5*r*radius});
const at=(q,r)=>cells.find(cell=>cell.q===q&&cell.r===r);
assert.equal(choose(cells,64,null,viewport,radius),at(0,0),'Start at screen center');
assert.equal(choose(cells,66,at(0,0),viewport,radius),at(1,0),'Small interval stays nearby');
assert.equal(choose(cells,66,at(5,0),viewport,radius),at(8,-2),'Keep spatial continuity instead of recentering every note');
assert.equal(choose(cells,46,at(-8,0),viewport,radius),choose(cells,46,null,viewport,radius),'Offscreen next step returns to centermost match');
assert.equal(choose(cells,66,at(20,0),viewport,radius),choose(cells,66,null,viewport,radius),'Resize invalidating anchor recenters');
assert.equal(choose(cells,null,at(0,0),viewport,radius),undefined,'Silence hides indicator');
assert.equal(choose(cells,200,null,viewport,radius),undefined,'Unavailable pitch is safe');
const kept=choose(cells,66,at(5,0),viewport,radius);
assert.equal(choose(cells,66,kept,viewport,radius),kept,'Repeated detections remain stable');
const shuffled=[...cells].reverse();
assert.deepEqual(choose(shuffled,66,at(5,0),viewport,radius),kept,'Cell enumeration order cannot change the route');
console.log('Detected-pitch placement passes: central start, local movement, offscreen reset, resize, silence, repeated pitches and enumeration stability.');

const chord=mod.exports.detectedChordCells;
const initial=chord(cells,[64,68,71],[],viewport,radius);
assert.equal(initial.length,3);
assert.ok(initial.every(cell=>cell.note===64||cell.note===68||cell.note===71));
assert.deepEqual(chord(cells,[71,64,68,64],initial,viewport,radius),initial,'Stable across ordering and duplicate detections');
const changed=chord(cells,[64,69,71],initial,viewport,radius);
for(const note of [64,71])assert.equal(changed.find(cell=>cell.note===note),initial.find(cell=>cell.note===note),'Common pitches keep their exact tiles');
const offcenter=[at(7,-2),at(8,-2)];
const local=chord(cells,[64,66],offcenter,viewport,radius);
assert.deepEqual(local,offcenter,'Repeated voicing stays local instead of jumping back to center');
const wrap=chord(cells,[66,68],offcenter,viewport,radius);
assert.deepEqual(wrap,chord(cells,[66,68],[],viewport,radius),'An offscreen chord tone recenters the whole voicing');
assert.notEqual(wrap.find(cell=>cell.note===66),offcenter[1],'Common tones move with the recentered voicing');
assert.deepEqual(chord(cells,[],initial,viewport,radius),[],'Silence clears visible chord notes');
assert.deepEqual(chord(cells,[64,68,71],initial,{left:-200,top:-250,width:400,height:500},radius),chord(cells,[64,68,71],[],{left:-200,top:-250,width:400,height:500},radius));
console.log('Detected chords pass: central placement, local continuity, common tones, whole-voicing recentering, resize, silence and detector ordering.');
